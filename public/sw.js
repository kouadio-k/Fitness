// Service worker minimal : l'application reste utilisable hors connexion.
// - Pages : réseau d'abord, cache en secours.
// - Fichiers statiques (JS/CSS/icônes, noms versionnés par Vite) : cache d'abord.
// - Open Food Facts et autres domaines : jamais mis en cache.
const CACHE = 'bemis-fitness-v2';

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(['./', './index.html', './manifest.webmanifest', './icon.svg'])));
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    // Autres pages du site (page de test, par exemple) : laissées au navigateur, pour ne jamais
    // remplacer la page de l'appli gardée en cache pour le hors connexion.
    if (!url.pathname.endsWith('/') && !url.pathname.endsWith('/index.html')) return;
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./index.html', copy));
          return res;
        })
        .catch(() => caches.match('./index.html')),
    );
    return;
  }

  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
